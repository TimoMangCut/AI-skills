#!/usr/bin/env python3
"""Cross-platform bootstrap installer/uninstaller for LocalSec AI-skills (Windows / macOS / Linux).

Can be invoked via:
  - PowerShell (Windows):  .\\AI-skills\\setup.ps1   (or .\\AI-skills\\setup.ps1 --uninstall)
  - CMD (Windows):         AI-skills\\setup.bat      (or AI-skills\\setup.bat --uninstall)
  - Python (Any OS):       python AI-skills/setup_bootstrap.py
  - Git Bash / POSIX sh:   sh AI-skills/setup.sh     (or sh AI-skills/setup.sh --uninstall)
"""
from __future__ import annotations

import os
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

BRIDGE_MARKER = "# AI-SKILLS-BRIDGE: auto-generated by setup_bootstrap.py"


def _resolve_git_exclude(root: Path) -> Path | None:
    git_entry = root / ".git"
    if git_entry.is_dir():
        info_dir = git_entry / "info"
        info_dir.mkdir(parents=True, exist_ok=True)
        return info_dir / "exclude"
    if git_entry.is_file():
        txt = git_entry.read_text(encoding="utf-8", errors="replace").strip()
        if txt.startswith("gitdir:"):
            git_dir = (root / txt.split(":", 1)[1].strip()).resolve()
            info_dir = git_dir / "info"
            info_dir.mkdir(parents=True, exist_ok=True)
            return info_dir / "exclude"
    return None


def _is_git_tracked(root: Path, rel_path: str) -> bool:
    if not (root / ".git").exists():
        return False
    try:
        res = subprocess.run(
            ["git", "-C", str(root), "ls-files", "--error-unmatch", rel_path],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
        return res.returncode == 0
    except OSError:
        return False


def _merge_marked_file(src_path: Path, dst_path: Path, marker_name: str, folder_name: str = "AI-skills") -> str:
    begin_tag = f"<!-- BEGIN AI-SKILLS:{marker_name} -->"
    end_tag = f"<!-- END AI-SKILLS:{marker_name} -->"
    src_text = src_path.read_text(encoding="utf-8").strip()
    if folder_name != "AI-skills":
        src_text = src_text.replace("AI-skills", folder_name)
    block = f"{begin_tag}\n{src_text}\n{end_tag}\n"

    if not dst_path.is_file():
        dst_path.write_text(block, encoding="utf-8")
        return "created"

    existing = dst_path.read_text(encoding="utf-8")
    if existing.strip() == src_text:
        dst_path.write_text(block, encoding="utf-8")
        return "updated"

    pattern = re.compile(re.escape(begin_tag) + r".*?" + re.escape(end_tag) + r"\n?", re.DOTALL)
    if pattern.search(existing):
        updated = pattern.sub(lambda _: block, existing)
        dst_path.write_text(updated, encoding="utf-8")
        return "updated"

    merged = existing.rstrip() + "\n\n" + block
    dst_path.write_text(merged, encoding="utf-8")
    return "merged_preserving_existing"


def _unmerge_marked_file(dst_path: Path, src_path: Path, marker_name: str) -> None:
    if not dst_path.is_file():
        return
    begin_tag = f"<!-- BEGIN AI-SKILLS:{marker_name} -->"
    end_tag = f"<!-- END AI-SKILLS:{marker_name} -->"
    existing = dst_path.read_text(encoding="utf-8")
    src_text = src_path.read_text(encoding="utf-8").strip()
    if existing.strip() == src_text:
        dst_path.unlink()
        return
    pattern = re.compile(r"\n*" + re.escape(begin_tag) + r".*?" + re.escape(end_tag) + r"\n?", re.DOTALL)
    remaining = pattern.sub("\n", existing).strip()
    if not remaining:
        dst_path.unlink()
    else:
        dst_path.write_text(remaining + "\n", encoding="utf-8")


def _install_localsec_bridge(project_root: Path, skill_dir: Path, folder_name: str) -> bool:
    bridge_dir = project_root / "localsec"
    bridge_init = bridge_dir / "__init__.py"
    if bridge_dir.exists() and not bridge_init.is_file():
        return False
    if bridge_init.is_file():
        existing = bridge_init.read_text(encoding="utf-8", errors="ignore")
        if BRIDGE_MARKER not in existing:
            return False
    bridge_dir.mkdir(parents=True, exist_ok=True)
    fallback_str = str((skill_dir / "localsec").resolve())
    code = (
        f"{BRIDGE_MARKER}\n"
        "from pathlib import Path as _Path\n\n"
        f"_cand = (_Path(__file__).resolve().parent.parent / {folder_name!r} / 'localsec').resolve()\n"
        f"_fallback = _Path({fallback_str!r})\n"
        "_real_pkg = _cand if _cand.is_dir() else _fallback\n"
        "if _real_pkg.is_dir():\n"
        "    __path__ = [str(_real_pkg)]\n"
    )
    bridge_init.write_text(code, encoding="utf-8")
    return True


def _remove_localsec_bridge(project_root: Path) -> None:
    bridge_dir = project_root / "localsec"
    bridge_init = bridge_dir / "__init__.py"
    if not bridge_init.is_file():
        return
    existing = bridge_init.read_text(encoding="utf-8", errors="ignore")
    if BRIDGE_MARKER not in existing:
        return
    shutil.rmtree(bridge_dir, ignore_errors=True)


def _resolve_working_python_cmd() -> str | None:
    """Return the first Python command that can actually start and import sys (preferring a real `sys.executable` over `WindowsApps` aliases)."""
    seen: set[str] = set()
    cands: list[str] = []
    if sys.executable and Path(sys.executable).is_file() and "WindowsApps" not in str(sys.executable):
        cands.append(sys.executable)
    cands.extend(["python", "python3", "py", sys.executable])
    for cand in cands:
        if not cand or cand in seen:
            continue
        seen.add(cand)
        if cand != sys.executable and shutil.which(cand) is None:
            continue
        try:
            res = subprocess.run(
                [cand, "-c", "import sys"],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=10,
                check=False,
            )
            if res.returncode == 0:
                return cand
        except Exception:  # noqa: BLE001
            continue
    return None


def _unquoted_path(p: Path) -> str:
    """Path usable in a hook command WITHOUT quotes, with forward slashes.

    - Antigravity on Windows passes the hook command to cmd.exe with inner quotes escaped as \\", so a quoted path
      reaches cmd/python as a literal `\\"C:/...\\"` (`is not recognized` / `can't open file 'C:\\\\"C:...'`) and the
      failing hook blocks every tool call in the workspace.
    - Claude Code runs hooks through Git Bash on Windows, which eats unquoted backslashes (`C:\\Users` -> `C:Users`).
    cmd.exe and Git Bash both accept `C:/Users/x/python.exe`. Paths with spaces use the 8.3 short name.
    """
    s = str(p.resolve())
    if " " in s and os.name == "nt":
        try:
            import ctypes

            buf = ctypes.create_unicode_buffer(1024)
            if ctypes.windll.kernel32.GetShortPathNameW(s, buf, 1024) and " " not in buf.value:
                s = buf.value
        except Exception:  # noqa: BLE001
            pass
    s = s.replace("\\", "/")
    return s if " " not in s else f'"{s}"'


def _guard_commands(py_cmd: str, skill_dir: Path) -> tuple[str, str]:
    """(claude_cmd, antigravity_cmd): absolute interpreter + absolute guard script, no quotes, no dependence on the
    hook runner's cwd (`python -m localsec...` only resolves from <Project-Root>)."""
    exe = shutil.which(py_cmd) or py_cmd
    if (
        py_cmd in {"python", "python3", "py"}
        and sys.executable
        and Path(sys.executable).is_file()
        and "WindowsApps" not in str(sys.executable)
    ):
        exe = sys.executable
    py = _unquoted_path(Path(exe)) if Path(exe).is_file() else py_cmd
    guard = _unquoted_path(skill_dir / "localsec" / "claude_subagent_guard.py")
    return f"{py} {guard} --mode blinded_challenger", f"{py} {guard} --platform antigravity"


def _rewrite_hook_python_cmd(project_root: Path, py_cmd: str, skill_dir: Path | None = None) -> None:
    """Pin both installed hook commands (Claude agent + Antigravity hooks.json) to _guard_commands()."""
    if not py_cmd or skill_dir is None:
        return
    claude_cmd, ag_cmd = _guard_commands(py_cmd, skill_dir)
    cl_agent = project_root / ".claude" / "agents" / "localsec-blinded-challenger.md"
    if cl_agent.is_file():
        txt = cl_agent.read_text(encoding="utf-8")
        txt = re.sub(
            r"(?m)^(\s*command:\s*).*claude_subagent_guard.*$",
            lambda m: m.group(1) + "'" + claude_cmd.replace("'", "''") + "'",
            txt,
        )
        cl_agent.write_text(txt, encoding="utf-8")

    ag_hooks = project_root / ".agents" / "hooks.json"
    if ag_hooks.is_file():
        try:
            data = json.loads(ag_hooks.read_text(encoding="utf-8"))
            guard_cfg = data.get("localsec-blinded-guard")
            if isinstance(guard_cfg, dict):
                for entry in guard_cfg.get("PreToolUse") or []:
                    for hk in (entry.get("hooks") if isinstance(entry, dict) else None) or []:
                        if isinstance(hk, dict) and hk.get("type", "command") == "command":
                            hk["command"] = ag_cmd
                ag_hooks.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        except Exception:  # noqa: BLE001
            pass


def _installed_hook_commands(project_root: Path) -> tuple[str | None, str | None]:
    claude_cmd = ag_cmd = None
    cl_agent = project_root / ".claude" / "agents" / "localsec-blinded-challenger.md"
    if cl_agent.is_file():
        m = re.search(r"(?m)^\s*command:\s*(?:'(.*)'|\"(.*)\"|(.*))\s*$", cl_agent.read_text(encoding="utf-8"))
        if m:
            claude_cmd = m.group(1).replace("''", "'") if m.group(1) is not None else (m.group(2) or m.group(3))
    ag_hooks = project_root / ".agents" / "hooks.json"
    if ag_hooks.is_file():
        try:
            ag_cmd = json.loads(ag_hooks.read_text(encoding="utf-8"))["localsec-blinded-guard"]["PreToolUse"][0]["hooks"][0]["command"]
        except Exception:  # noqa: BLE001
            ag_cmd = None
    return claude_cmd, ag_cmd


def _git_bash() -> str | None:
    """Git Bash used by Claude Code on Windows (not WSL's System32\\bash.exe, which cannot run C:/ paths)."""
    cands = [os.environ.get("CLAUDE_CODE_GIT_BASH_PATH", "")]
    git = shutil.which("git")
    if git:
        gp = Path(git).resolve()
        cands += [str(gp.parent.parent / "bin" / "bash.exe"), str(gp.parent.parent.parent / "bin" / "bash.exe")]
    cands += [r"C:\Program Files\Git\bin\bash.exe", r"C:\Program Files (x86)\Git\bin\bash.exe"]
    return next((c for c in cands if c and Path(c).is_file()), None)


def _self_check_blinded_guard(project_root: Path, _py_cmd: str | None = None) -> int:
    """Run the INSTALLED hook command strings exactly the way each tool runs them, from a directory that is not
    <Project-Root>. (The previous self-check called the interpreter directly from <Project-Root>, so it passed
    while the installed commands failed inside Antigravity and Claude Code.)

    - Claude Code: exit code must be 2 for a forbidden read (any other code is a NON-blocking hook error, i.e. the
      guard silently switches off). Checked through cmd.exe and, on Windows, Git Bash.
    - Antigravity: stdout must be {"decision": "deny"} for a 2.3 transcript and "allow" otherwise, exit code 0.
      Run as subprocess(["cmd", "/c", command]) so inner quotes get escaped as \\" exactly like Antigravity does.
    """
    import tempfile

    claude_cmd, ag_cmd = _installed_hook_commands(project_root)
    if not claude_cmd and not ag_cmd:
        print("[WARN] Blinded guard self-check: no installed hook command found.", file=sys.stderr)
        return 1
    probe_claude = '{"tool_name": "Read", "tool_input": {"file_path": ".localsec/tmp/deep_trace_chain_analyst_probe.json"}}'
    with tempfile.TemporaryDirectory() as tmp:
        if claude_cmd:
            shells: list[tuple[str, list[str]]] = [
                ("cmd" if os.name == "nt" else "sh", (["cmd", "/c", claude_cmd] if os.name == "nt" else ["sh", "-c", claude_cmd]))
            ]
            gb = _git_bash() if os.name == "nt" else None
            if gb:
                shells.append(("git-bash", [gb, "-c", claude_cmd]))
            for name, argv in shells:
                try:
                    res = subprocess.run(argv, input=probe_claude, capture_output=True, text=True, cwd=tmp, timeout=60, check=False)
                except Exception as exc:  # noqa: BLE001
                    print(f"[WARN] Blinded guard self-check: Claude hook could not start via {name} ({type(exc).__name__}: {exc}).", file=sys.stderr)
                    return 1
                if res.returncode != 2:
                    print(
                        f"[WARN] Blinded guard self-check FAILED: Claude hook via {name} returned {res.returncode} instead of 2 "
                        f"(guard would be OFF). Command: {claude_cmd}\n{res.stderr.strip()[:300]}",
                        file=sys.stderr,
                    )
                    return 1
        if ag_cmd:
            tr = Path(tmp) / "t.jsonl"
            tr.write_text(json.dumps({"content": "/phase-2-blinded-counterevidence-challenger probe"}) + "\n", encoding="utf-8")
            call = {"name": "view_file", "args": {"AbsolutePath": ".localsec/tmp/deep_trace_chain_analyst_probe.json"}}
            argv = ["cmd", "/c", ag_cmd] if os.name == "nt" else ["sh", "-c", ag_cmd]
            for transcript, want in ((str(tr), "deny"), ("", "allow")):
                try:
                    res = subprocess.run(
                        argv,
                        input=json.dumps({"toolCall": call, "transcriptPath": transcript}),
                        capture_output=True,
                        text=True,
                        cwd=tmp,
                        timeout=60,
                        check=False,
                    )
                    got = json.loads(res.stdout or "{}").get("decision")
                except Exception as exc:  # noqa: BLE001
                    print(f"[WARN] Blinded guard self-check: Antigravity hook could not run ({type(exc).__name__}: {exc}).", file=sys.stderr)
                    return 1
                if res.returncode != 0 or got != want:
                    print(
                        f"[WARN] Blinded guard self-check FAILED: Antigravity hook expected {want}, got rc={res.returncode} decision={got!r} "
                        f"(a failing hook blocks EVERY tool call). Command: {ag_cmd}\n{res.stderr.strip()[:300]}",
                        file=sys.stderr,
                    )
                    return 1
    print("[OK] Blinded guard self-check passed (installed Claude + Antigravity hook commands work from any cwd).")
    return 0



def _merge_antigravity_hooks(dst: Path, src: Path, remove: bool = False) -> None:
    """Add (or remove) the toolkit's named hooks in the workspace `.agents/hooks.json`, keeping the user's own hooks."""
    if not src.is_file():
        return
    ours = json.loads(src.read_text(encoding="utf-8"))
    current: dict = {}
    if dst.is_file():
        try:
            current = json.loads(dst.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            current = {}
    for k in ours:
        current.pop(k, None)
    if not remove:
        current.update(ours)
    if current:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(json.dumps(current, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    elif dst.is_file():
        dst.unlink()


def _update_git_exclude(root: Path, skill_folder: str, has_bridge: bool = True, remove: bool = False) -> bool:
    exclude_file = _resolve_git_exclude(root)
    if exclude_file is None:
        return False
    begin_tag = "# BEGIN AI-SKILLS EXCLUDE"
    end_tag = "# END AI-SKILLS EXCLUDE"
    existing = exclude_file.read_text(encoding="utf-8") if exclude_file.is_file() else ""
    pattern = re.compile(r"\n*" + re.escape(begin_tag) + r".*?" + re.escape(end_tag) + r"\n?", re.DOTALL)
    cleaned = pattern.sub("\n", existing).rstrip()
    if remove:
        exclude_file.write_text((cleaned + "\n") if cleaned else "", encoding="utf-8")
        return True

    entries = [
        f"/{skill_folder}/",
        "/.agents/README.md",
        "/.agents/rules/soul.md",
        "/.agents/agents/localsec-*",
        "/.agents/skills/phase-1-*",
        "/.agents/skills/phase-2-*",
        "/.agents/skills/phase-3-*",
        "/.agents/skills/phase-4-*",
        "/.agents/skills/phase-risk-*",
        "/.claude/skills/phase-1-*",
        "/.claude/skills/phase-2-*",
        "/.claude/skills/phase-3-*",
        "/.claude/skills/phase-4-*",
        "/.claude/skills/phase-risk-*",
        "/.claude/agents/localsec-*",
        "/.localsec/",
        "/documents/",
    ]
    if has_bridge and not _is_git_tracked(root, "localsec"):
        entries.append("/localsec/")
    for root_doc in ("AGENTS.md", "SOUL.md", "CLAUDE.md"):
        if not _is_git_tracked(root, root_doc):
            entries.append(f"/{root_doc}")
    block = begin_tag + "\n" + "\n".join(entries) + "\n" + end_tag + "\n"
    new_content = (cleaned + "\n\n" + block) if cleaned else block
    exclude_file.write_text(new_content, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    # Ensure UTF-8 stdout/stderr on Windows consoles
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(encoding="utf-8")
            except Exception:
                pass

    raw_args = list(sys.argv[1:] if argv is None else argv)
    replace_foreign = False
    args: list[str] = []
    for a in raw_args:
        if a in ("--replace-foreign", "-ReplaceForeign"):
            replace_foreign = True
        else:
            args.append(a)

    skill_dir = Path(__file__).resolve().parent
    project_root = Path.cwd().resolve()
    folder_name = skill_dir.name
    mode = "install"

    if len(args) >= 3 and Path(args[0]).exists() and Path(args[1]).exists():
        skill_dir = Path(args[0]).resolve()
        project_root = Path(args[1]).resolve()
        folder_name = args[2]
        mode = args[3] if len(args) >= 4 else "install"
    elif len(args) >= 1:
        mode = args[0]

    if skill_dir == project_root:
        print(f"[!] Bạn đang đứng bên trong thư mục {folder_name}.")
        print("    Hãy cd ra thư mục gốc của Project cần áp dụng (<Project-Root>) rồi chạy:")
        print(f"    - PowerShell (Windows):  .\\{folder_name}\\setup.ps1")
        print(f"    - CMD (Windows):         {folder_name}\\setup.bat")
        print(f"    - Git Bash / Linux:      sh {folder_name}/setup.sh")
        return 1

    if mode in ("--uninstall", "--clean", "uninstall", "clean", "-Uninstall", "-Clean"):
        agents_dir = project_root / ".agents"
        if (agents_dir / "skills").is_dir():
            for sp in (skill_dir / ".agents" / "skills").iterdir():
                if sp.is_dir():
                    target_sp = agents_dir / "skills" / sp.name
                    if target_sp.exists():
                        shutil.rmtree(target_sp)
        soul_rule = agents_dir / "rules" / "soul.md"
        if soul_rule.is_file():
            soul_rule.unlink()
        if (skill_dir / ".agents" / "agents").is_dir():
            for ap in (skill_dir / ".agents" / "agents").iterdir():
                if (agents_dir / "agents" / ap.name).is_file():
                    (agents_dir / "agents" / ap.name).unlink()
        _merge_antigravity_hooks(agents_dir / "hooks.json", skill_dir / ".agents" / "hooks.json", remove=True)
        readme_ag = agents_dir / "README.md"
        if readme_ag.is_file():
            readme_ag.unlink()
        for sub in ("skills", "rules", "agents"):
            subdir = agents_dir / sub
            if subdir.is_dir() and not any(subdir.iterdir()):
                subdir.rmdir()
        if agents_dir.is_dir() and not any(agents_dir.iterdir()):
            agents_dir.rmdir()

        claude_dir = project_root / ".claude"
        if (claude_dir / "skills").is_dir():
            for sp in (skill_dir / ".agents" / "skills").iterdir():
                if sp.is_dir():
                    target_sp = claude_dir / "skills" / sp.name
                    if target_sp.exists():
                        shutil.rmtree(target_sp)
            if not any((claude_dir / "skills").iterdir()):
                (claude_dir / "skills").rmdir()
        if (claude_dir / "agents").is_dir() and (skill_dir / ".claude" / "agents").is_dir():
            for ap in (skill_dir / ".claude" / "agents").iterdir():
                if ap.is_file():
                    target_ap = claude_dir / "agents" / ap.name
                    if target_ap.is_file():
                        target_ap.unlink()
            if not any((claude_dir / "agents").iterdir()):
                (claude_dir / "agents").rmdir()
        if claude_dir.is_dir() and not any(claude_dir.iterdir()):
            claude_dir.rmdir()

        _remove_localsec_bridge(project_root)
        _unmerge_marked_file(project_root / "AGENTS.md", skill_dir / "AGENTS.md", "AGENTS.md")
        _unmerge_marked_file(project_root / "SOUL.md", skill_dir / "SOUL.md", "SOUL.md")
        if (skill_dir / "CLAUDE.md").is_file():
            _unmerge_marked_file(project_root / "CLAUDE.md", skill_dir / "CLAUDE.md", "CLAUDE.md")
        _update_git_exclude(project_root, folder_name, remove=True)
        print(f"[✓] Đã gỡ cài đặt các file AI-skills khỏi {project_root} (giữ nguyên mọi nội dung gốc của dự án).")
        return 0

    # 1. Sync .agents/ (Antigravity) and .claude/skills/ + .claude/agents/ (Claude Code)
    agents_dst = project_root / ".agents"
    claude_dst = project_root / ".claude"
    (agents_dst / "skills").mkdir(parents=True, exist_ok=True)
    (agents_dst / "rules").mkdir(parents=True, exist_ok=True)
    (claude_dst / "skills").mkdir(parents=True, exist_ok=True)
    (claude_dst / "agents").mkdir(parents=True, exist_ok=True)
    (project_root / ".localsec" / "tmp").mkdir(parents=True, exist_ok=True)

    our_skills = {sp.name for sp in (skill_dir / ".agents" / "skills").iterdir() if sp.is_dir()}
    our_agents = set()
    if (skill_dir / ".claude" / "agents").is_dir():
        our_agents.update(ap.name for ap in (skill_dir / ".claude" / "agents").iterdir() if ap.is_file())
    if (skill_dir / ".agents" / "agents").is_dir():
        our_agents.update(ap.name for ap in (skill_dir / ".agents" / "agents").iterdir() if ap.is_file())

    foreign_entries: list[str] = []
    for skill_parent, label in ((agents_dst / "skills", ".agents/skills"), (claude_dst / "skills", ".claude/skills")):
        if skill_parent.is_dir():
            for child in sorted(skill_parent.iterdir()):
                if child.name not in our_skills:
                    foreign_entries.append(f"{label}/{child.name}")
                    if replace_foreign:
                        if child.is_dir():
                            shutil.rmtree(child)
                        else:
                            child.unlink()
    for agent_parent, label in ((agents_dst / "agents", ".agents/agents"), (claude_dst / "agents", ".claude/agents")):
        if agent_parent.is_dir():
            for child in sorted(agent_parent.iterdir()):
                if child.name not in our_agents:
                    foreign_entries.append(f"{label}/{child.name}")
                    if replace_foreign:
                        if child.is_dir():
                            shutil.rmtree(child)
                        else:
                            child.unlink()

    shutil.copy2(skill_dir / ".agents" / "README.md", agents_dst / "README.md")
    if (skill_dir / ".agents" / "rules" / "soul.md").is_file():
        shutil.copy2(skill_dir / ".agents" / "rules" / "soul.md", agents_dst / "rules" / "soul.md")

    copied_skills = 0
    for sp in sorted((skill_dir / ".agents" / "skills").iterdir()):
        if sp.is_dir():
            target_ag = agents_dst / "skills" / sp.name
            if target_ag.exists():
                shutil.rmtree(target_ag)
            shutil.copytree(sp, target_ag)

            cl_src = skill_dir / ".claude" / "skills" / sp.name
            target_cl = claude_dst / "skills" / sp.name
            if target_cl.exists():
                shutil.rmtree(target_cl)
            shutil.copytree(cl_src if cl_src.is_dir() else sp, target_cl)
            copied_skills += 1

    if (skill_dir / ".claude" / "agents").is_dir():
        for ap in sorted((skill_dir / ".claude" / "agents").iterdir()):
            if ap.is_file():
                shutil.copy2(ap, claude_dst / "agents" / ap.name)

    # Antigravity: custom subagent definitions + workspace PreToolUse hook (same guard as the Claude agent hook)
    if (skill_dir / ".agents" / "agents").is_dir():
        (agents_dst / "agents").mkdir(parents=True, exist_ok=True)
        for ap in sorted((skill_dir / ".agents" / "agents").iterdir()):
            if ap.is_file():
                shutil.copy2(ap, agents_dst / "agents" / ap.name)
    _merge_antigravity_hooks(agents_dst / "hooks.json", skill_dir / ".agents" / "hooks.json")

    # 2. Rewrite folder references if cloned under a custom folder name != AI-skills
    if folder_name != "AI-skills":
        for root_target in (agents_dst, claude_dst / "skills", claude_dst / "agents"):
            for md in root_target.rglob("*.md"):
                txt = md.read_text(encoding="utf-8")
                md.write_text(txt.replace("AI-skills", folder_name), encoding="utf-8")

    # 3. Install package bridge <Project-Root>/localsec/__init__.py so `python -m localsec.manual_session` works on Windows PowerShell/CMD without PYTHONPATH
    has_bridge = _install_localsec_bridge(project_root, skill_dir, folder_name)

    # 3b. Resolve working Python interpreter and self-check both Claude and Antigravity blinded-step hooks
    py_cmd = _resolve_working_python_cmd()
    if py_cmd:
        _rewrite_hook_python_cmd(project_root, py_cmd, skill_dir=skill_dir)
    if _self_check_blinded_guard(project_root, _py_cmd=py_cmd) != 0:
        if os.environ.get("AI_SKILLS_ALLOW_UNGUARDED", "0") != "1":
            print("[!] Dừng setup. Sửa lỗi trên, hoặc đặt AI_SKILLS_ALLOW_UNGUARDED=1 nếu chấp nhận bước mù không được bảo vệ.", file=sys.stderr)
            return 3

    # 4. Non-destructively install or merge AGENTS.md, SOUL.md, and CLAUDE.md
    agents_status = _merge_marked_file(skill_dir / "AGENTS.md", project_root / "AGENTS.md", "AGENTS.md", folder_name=folder_name)
    soul_status = _merge_marked_file(skill_dir / "SOUL.md", project_root / "SOUL.md", "SOUL.md", folder_name=folder_name)
    claude_status = (
        _merge_marked_file(skill_dir / "CLAUDE.md", project_root / "CLAUDE.md", "CLAUDE.md", folder_name=folder_name)
        if (skill_dir / "CLAUDE.md").is_file()
        else "skipped"
    )

    # 5. Update .git/info/exclude so target project git status stays clean
    exclude_updated = _update_git_exclude(project_root, folder_name, has_bridge=has_bridge, remove=False)

    print(f"[+] Đã đồng bộ {copied_skills} skills vào .agents/skills/ (Antigravity) và .claude/skills/ (Claude Code)")
    if foreign_entries:
        if replace_foreign:
            print(f"[!] Đã gỡ {len(foreign_entries)} skill/agent ngoại lai (--replace-foreign): {', '.join(foreign_entries[:10])}")
        else:
            print(f"[i] Phát hiện {len(foreign_entries)} skill/agent riêng của dự án (được giữ nguyên; truyền --replace-foreign nếu muốn dọn sạch): {', '.join(foreign_entries[:10])}")
    print(f"[+] Trạng thái AGENTS.md: {agents_status} | SOUL.md: {soul_status} | CLAUDE.md: {claude_status}")
    if has_bridge:
        print("[+] Đã tạo cầu nối package localsec (chạy trực tiếp `python -m localsec.manual_session` trên PowerShell/CMD/Bash).")
    print("[+] Thư mục trạng thái chuẩn (Run Directory): .localsec/runs/default/<repo_slug>/")
    if exclude_updated:
        print("[+] Đã cập nhật .git/info/exclude để giữ sạch 'git status' cho Project.")
    print(f"[+] Toàn bộ Engine & Schemas được giữ gọn trong: {skill_dir}")

    if os.environ.get("AI_SKILLS_SKIP_TESTS", "0") != "1":
        print("[*] Đang kiểm tra kết nối CLI & Unit Tests...")
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join([str(skill_dir), str(project_root)])
        res = subprocess.run(
            [sys.executable, "-m", "unittest", "discover", "-s", str(skill_dir / "tests")],
            cwd=str(project_root),
            env=env,
            check=False,
        )
        if res.returncode != 0:
            return res.returncode

    print(
        f"[✓] Sẵn sàng! Hãy mở {project_root} trong Antigravity hoặc Claude Code và chạy "
        "/phase-1-orchestrator, /phase-2-orchestrator, /phase-3-orchestrator, hoặc /phase-4-orchestrator."
    )
    return 0


